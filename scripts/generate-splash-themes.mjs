// Generates android/app/src/main/res/values/splash_themes.xml: one launch-screen style per app background colour.
//
// The Android 12+ system launch screen takes its colour from a *style*, which cannot be built at run time. The app
// therefore ships one tiny style per possible --bg (6 style presets x 3 modes + 10 mono hues x 3 modes) and, on
// Android 13+, picks the right one with Context.setSplashScreenTheme (see LaunchBackground.java). The names are
// `Splash_<bg hex without #, lowercase>`, so the web layer only has to send the hex of the current --bg.
//
// Run again whenever a --bg value in src/index.css (or the src/styles/*.css files it imports) or the mono palette in
// src/utils/themes.ts changes:
//   node scripts/generate-splash-themes.mjs
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
// src/index.css is only a list of @imports; inline the ./styles/*.css parts (in import order) before reading --bg.
const inlineStyles = async (file) => {
  const text = await readFile(file, 'utf8');
  const parts = await Promise.all(text.split('\n').map(async (line) => {
    const m = line.match(/^@import "\.\/(styles\/[^"]+)";/);
    return m ? inlineStyles(`${root}src/${m[1]}`) : line;
  }));
  return parts.join('\n');
};
const css = await inlineStyles(`${root}src/index.css`);
const MODES = ['light', 'lite-dark', 'dark'];
const colours = new Map(); // hex -> label

const add = (hex, label) => {
  const key = hex.toLowerCase();
  if (!/^#[0-9a-f]{6}$/.test(key)) throw new Error(`Unexpected colour ${hex} for ${label}`);
  if (!colours.has(key)) colours.set(key, label);
};
const bgOf = (selectorRegex, label) => {
  // A selector can appear in several blocks (e.g. :root); take the first one that sets --bg.
  for (const m of css.matchAll(new RegExp(`^${selectorRegex}\\s*\\{([^}]*)\\}`, 'gm'))) {
    const bg = m[1].match(/--bg:\s*(#[0-9a-fA-F]{6})/);
    if (bg) return add(bg[1], label);
  }
  throw new Error(`No --bg found for ${label}`);
};

// Classic: :root is Light, then the two dark modes.
bgOf(':root', 'classic light');
bgOf('\\[data-theme="lite-dark"\\]', 'classic lite-dark');
bgOf('\\[data-theme="dark"\\]', 'classic dark');
for (const style of ['angular', 'aurora', 'pop', 'playful', 'minimal']) {
  for (const mode of MODES) bgOf(`html\\[data-style="${style}"\\]\\[data-theme="${mode}"\\]`, `${style} ${mode}`);
}

// Mono: the background depends on the hue, computed by the app's own palette generator.
const bundled = await build({
  stdin: { contents: "export { getMonoVariables, MONO_HUES } from './src/utils/themes.ts';", resolveDir: root, loader: 'ts' },
  bundle: true, write: false, format: 'esm', platform: 'node',
});
const themes = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
for (const hue of themes.MONO_HUES) {
  for (const mode of MODES) add(themes.getMonoVariables(hue.hex, mode)['--bg'], `mono ${hue.id} ${mode}`);
}

const rows = [...colours].map(([hex, label]) =>
  `    <!-- ${label} -->\n    <style name="Splash_${hex.slice(1)}" parent="AppTheme.NoActionBarLaunch">\n        <item name="windowSplashScreenBackground">${hex}</item>\n    </style>`);
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by scripts/generate-splash-themes.mjs (do not hand-edit): one launch-screen style per app background
  colour, chosen at run time by LaunchBackground.java (Android 13+). ${colours.size} colours.
-->
<resources>
${rows.join('\n')}
</resources>
`;
await writeFile(`${root}android/app/src/main/res/values/splash_themes.xml`, xml);
console.log(`Wrote ${colours.size} launch-screen styles.`);
