#!/usr/bin/env node
// Writes the Kakcal launch animations and the overview sheet. Generated, never hand-edited:
//
//   src/assets/kakcalculator_intro/animations/01-soft-serve.svg ... 06-flush-return.svg   the six launch animations
//   src/assets/kakcalculator_intro/animations/wordmark-plop.svg                          the wordmark animation (design asset)
//   src/assets/kakcalculator_intro/logos-and-animations-overview.html                    gallery with replay buttons and a light / dark switch
//
// The animations themselves are defined in scripts/brand-animations.mjs. Their colours are the launch overlay's tokens
// (`var(--kc-cream, #F9F3E6)` = tile / page background, `var(--kc-ink, #0B0F1E)` = poop; src/components/intro/intro.css sets
// them per theme), so one file serves Light, Lite Dark and Dark. Their only time values are `NNNms` animation durations: the app
// divides them by INTRO_SPEED (src/components/intro/introAnimations.ts) to play them faster.
//
// Needs opentype.js (not a project dependency):  npm i --no-save opentype.js && node scripts/generate-intro-animations.mjs
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { LAUNCH, WORD_PLOP, launchSvg, wordmarkSvg } from './brand-animations.mjs';
import { PALETTE } from './brand-geometry.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const OUT = 'src/assets/kakcalculator_intro/';
const dir = path.join(root, OUT, 'animations');
const NOTE = '<!-- Generated by scripts/generate-intro-animations.mjs from scripts/brand-animations.mjs. Do not hand-edit. -->\n';

// The previous generation of files (and the lockups) go away; wordmark.svg belongs to scripts/outline-wordmark.mjs.
for (const f of await readdir(dir)) {
  if (f !== 'wordmark.svg') await rm(path.join(dir, f));
}

export const FILES = LAUNCH.map((a, i) => ({ ...a, file: `${String(i + 1).padStart(2, '0')}-${a.id}.svg` }));
const svgs = {};
for (const a of FILES) {
  svgs[a.id] = launchSvg(a);
  await writeFile(path.join(dir, a.file), NOTE + svgs[a.id] + '\n');
}
const word = wordmarkSvg();
await writeFile(path.join(dir, 'wordmark-plop.svg'), NOTE + word + '\n');

// ---------- overview sheet ----------
const logoFiles = ['kakcalculator-icon.svg', 'kakcalculator-icon-inverted.svg', 'kakcalculator-wordmark.svg', 'kakcalculator-wordmark-inverted.svg'];
const logos = [];
for (const f of logoFiles) logos.push([f, await readFile(path.join(root, OUT, 'logos', f), 'utf8')]);
const dataUri = (svg) => 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
const card = (a) => `<figure><div class="stage" data-id="${a.id}"></div><figcaption><b>${a.file.replace('.svg', '')}</b><span>${a.name} &middot; ${a.D} ms</span><p>${a.desc}</p><button type="button" data-replay="${a.id}">Replay</button></figcaption></figure>`;
const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kakcal &mdash; logo &amp; launch animation overview</title>
<!-- Generated by scripts/generate-intro-animations.mjs. Do not hand-edit. -->
<style>
:root{--kc-ink:${PALETTE.light.ink};--kc-cream:${PALETTE.light.bg};--page:#EFE9DD;--text:#0B0F1E}
[data-dark=true]{--kc-ink:${PALETTE.dark.ink};--kc-cream:${PALETTE.dark.bg};--page:#10162A;--text:#F9F3E6}
body{margin:0;padding:24px;background:var(--page);color:var(--text);font:15px/1.45 system-ui,sans-serif}
h1{font-size:22px;margin:0 0 4px}h2{font-size:16px;margin:28px 0 10px}
.bar{display:flex;gap:10px;align-items:center;margin:10px 0 0}
button{font:inherit;padding:6px 12px;border-radius:999px;border:1px solid currentColor;background:transparent;color:inherit;cursor:pointer}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(230px,1fr));gap:18px}
figure{margin:0;padding:14px;border-radius:18px;border:1px solid color-mix(in srgb,var(--text) 18%,transparent)}
.stage{width:160px;height:160px;margin:0 auto 10px}.stage>svg{width:100%;height:100%;display:block;overflow:visible}
figcaption b{display:block}figcaption span{opacity:.7;font-size:13px}figcaption p{margin:6px 0 10px;font-size:13px}
.logos{display:flex;flex-wrap:wrap;gap:16px;align-items:center}.logos img{height:110px;border-radius:12px}
.word{height:110px}.word>svg{height:100%;width:auto}
</style>
</head>
<body>
<h1>Kakcal &mdash; logo &amp; launch animations</h1>
<p>The icon is the solid poop with the K carved out of its belly; the name is k + poop + kcal. The six launch animations end on the exact icon. Durations below are the file's own; the app plays them faster (<code>INTRO_SPEED</code>).</p>
<div class="bar"><button type="button" id="theme">Switch to dark</button><button type="button" id="all">Replay all</button></div>
<h2>Logos</h2>
<div class="logos">${logos.map(([f, svg]) => `<img alt="${f}" title="${f}" src="${dataUri(svg)}">`).join('')}</div>
<h2>Launch animations</h2>
<div class="grid">${FILES.map(card).join('')}</div>
<h2>Wordmark animation</h2>
<div class="word" data-word></div><div class="bar"><button type="button" data-replay="word">Replay</button> <span>${WORD_PLOP.name} &middot; ${WORD_PLOP.D} ms</span></div>
<script>
const SVGS = ${JSON.stringify({ ...svgs, word }).replace(/</g, '\\u003c')};
const stage = (id) => (id === 'word' ? document.querySelector('[data-word]') : document.querySelector('[data-id="' + id + '"]'));
const play = (id) => { const el = stage(id); el.innerHTML = ''; void el.offsetWidth; el.innerHTML = SVGS[id]; };
Object.keys(SVGS).forEach(play);
document.addEventListener('click', (e) => { const b = e.target.closest('[data-replay]'); if (b) play(b.dataset.replay); });
document.getElementById('all').onclick = () => Object.keys(SVGS).forEach(play);
document.getElementById('theme').onclick = (e) => { const d = document.body.parentElement.dataset.dark !== 'true'; document.documentElement.dataset.dark = d; e.target.textContent = d ? 'Switch to light' : 'Switch to dark'; };
</script>
</body>
</html>
`;
await writeFile(path.join(root, OUT, 'logos-and-animations-overview.html'), html);
console.log('wrote', FILES.map((a) => a.file).join(', '), '+ wordmark-plop.svg + the overview sheet');
