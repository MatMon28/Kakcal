#!/usr/bin/env node
// Writes src/components/common/poop-anim.css: the logo-press animations (what happens when the wordmark in the header is
// tapped), generated from scripts/brand-animations.mjs, where each animation is defined once for the SVG previews and the app.
//
// The wordmark's poop (scripts/outline-wordmark.mjs) is `.kc-poop-group > .kc-m.kc-poop > .kc-m.kc-t3 / kc-t2 / kc-t1 / kc-tip`;
// `Brand.tsx` adds the three burst ticks (`.kc-poop-ticks > .kc-tick`). `data-poop-anim="<id>"` on `.kc-wordmark` starts one.
// Durations must match POOP_ANIMATIONS in src/components/common/poopAnimations.ts (scripts/smoke.mjs checks it).
//
// Needs opentype.js (not a project dependency):  npm i --no-save opentype.js && node scripts/generate-poop-animations.mjs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PRESS_ANIMATIONS } from './brand-animations.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const classes = (css) => css.replace(/\.(poop|t3|t2|t1|tip|tick|m)(?![\w-])/g, '.kc-$1');

let out = `/*
 * Logo-click poop animations (see poopAnimations.ts and docs/motion.md). GENERATED by scripts/generate-poop-animations.mjs
 * from scripts/brand-animations.mjs: do not hand-edit, change the definition there and run the script again.
 *
 * The wordmark SVG (Brand.tsx) marks the solid poop of the wordmark:
 *   .kc-poop          the whole poop            .kc-t3 .kc-t2 .kc-t1  the three tiers, bottom to top
 *   .kc-tip           the pointed tip           .kc-tick              three burst ticks around the poop (Brand.tsx adds them)
 * \`data-poop-anim="<id>"\` on \`.kc-wordmark\` starts the matching animation: ${PRESS_ANIMATIONS.map((a) => `${a.id} (${a.D} ms)`).join(', ')}.
 * Transform / opacity / stroke-dashoffset only; every animation ends exactly on the resting poop and nothing loops.
 * The poop group is scaled about 1.92 in the wordmark, so the pixel values below are in the poop's own units.
 */

/* Let the poop leave the wordmark's viewBox while it jumps or falls in. */
.kc-wordmark > svg {
  overflow: visible;
}

.kc-wordmark .kc-m {
  transform-box: fill-box;
  transform-origin: 50% 50%;
}

.kc-wordmark .kc-poop-ticks .kc-tick {
  opacity: 0;
}
`;
for (const a of PRESS_ANIMATIONS) {
  const scope = `.kc-wordmark[data-poop-anim='${a.id}']`;
  let css = a.css.replaceAll('@keyframes', '§KF').replaceAll('&', scope).replaceAll('@', `kc-${a.id}-`).replaceAll('§KF', '@keyframes ');
  css = classes(css).replace(/(\})(?=\S)/g, '$1\n').replace(/(\n)\s*@keyframes/g, '$1@keyframes');
  out += `\n/* ---------- ${a.id}: ${a.desc} ---------- */\n${scope} {\n  --d: ${a.D}ms;\n}\n${css}\n`;
}
out += `
@media (prefers-reduced-motion: reduce) {
  .kc-wordmark .kc-poop-group *,
  .kc-wordmark .kc-poop-ticks * {
    animation: none !important;
  }
}
`;
await writeFile(fileURLToPath(new URL('../src/components/common/poop-anim.css', import.meta.url)), out);
console.log(`wrote poop-anim.css (${PRESS_ANIMATIONS.length} animations)`);
